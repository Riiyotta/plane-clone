import { TUNE } from './phTune.js'

// Placeholder copy generator (brief content rule: paragraph-level prose is NOT copied from plane.so).
// ph(n, seed) returns neutral original English text of about n characters, so line wrapping and
// section heights stay close to the live page.
const POOL = [
  'Placeholder text that explains how teams plan, track, and report on all of their work.',
  'Roadmaps, docs, and team discussions stay together in one shared workspace.',
  'Admins manage access in one place while members keep the freedom they need.',
  'Progress is easy to see for a single project, a whole department, or the company.',
  'Automatic summaries give each stakeholder a clear update whenever they ask.',
  'New teammates learn their priorities quickly and can start to contribute sooner.',
  'Linked records keep specs, decisions, and delivery details connected over time.',
  'Custom workflows make approvals consistent without slowing anyone down.',
  'Deployment options support regulated teams and strict security reviews.',
  'Integrations keep your existing tools, alerts, and dashboards in sync.',
  'Flexible layouts show workloads, timelines, and milestones in a clear way.',
  'This neutral placeholder copy stands in for the original text on this page.',
  'Shared editing keeps everyone aligned while each change shows up right away.',
  'A clear hierarchy organizes goals, projects, and the work that repeats often.',
]

// raw generator (also used by the line-wrap tuning script)
export function gen(n, seed = 0) {
  if (!n) return ''
  let out = ''
  const sd = Math.abs(seed)
  let i = sd % POOL.length
  while (out.length < n + 160) {
    out += (out ? ' ' : '') + POOL[i]
    i = (i + 1) % POOL.length
  }
  // larger seeds start a few words into the sentence so every call site gets distinct copy
  const skip = Math.floor(sd / POOL.length) % 23
  if (skip) {
    const words = out.split(' ').slice(skip)
    words[0] = words[0].charAt(0).toUpperCase() + words[0].slice(1)
    out = words.join(' ')
  }
  // cut at a word boundary as close to n as possible
  let cut = out.lastIndexOf(' ', n)
  if (cut < n * 0.85) cut = out.indexOf(' ', n)
  let s = out.slice(0, cut).replace(/[,;:]$/, '')
  if (!/[.!?]$/.test(s)) s = s.replace(/\.?$/, '.')
  return s
}

// ph(): a tuning table (phTune.js) can swap (length, seed) for a variant of the same length (±10%) whose
// line wrapping matches the live copy at 1440 and 390. Generated by the measuring script.
export function ph(n, seed = 0) {
  const t = TUNE[`${n}:${seed}`]
  const out = t ? gen(t[0], t[1]) : gen(n, seed)
  // measuring hook: the tuning script sets window.__PH_MAP to learn which call produced which text
  if (typeof window !== 'undefined' && window.__PH_MAP) window.__PH_MAP.set(out, `${n}:${seed}`)
  return out
}

// Several lines (for copy that the live site breaks with <br>): ph.lines([62, 64]) -> 'a\nb'
ph.lines = (lens, seed = 0) => lens.map((n, k) => ph(n, seed + k * 3)).join('\n')
